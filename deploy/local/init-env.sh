#!/usr/bin/env bash
# Writes deploy/local/.env with fresh secrets for the local stack. Refuses to overwrite an existing file.
# Requires openssl (Ed25519 support, OpenSSL 1.1.1+).
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
TARGET="$HERE/.env"
if [[ -e "$TARGET" ]]; then
  echo "$TARGET already exists; delete it first to rotate every local secret." >&2
  exit 1
fi

secret() { openssl rand -hex 32; }
KEY_DIR="$(mktemp -d)"
trap 'rm -rf "$KEY_DIR"' EXIT
openssl genpkey -algorithm ed25519 -out "$KEY_DIR/capability.pem" 2>/dev/null
PRIVATE_DER_B64="$(openssl pkey -in "$KEY_DIR/capability.pem" -outform DER | openssl base64 -A)"
PUBLIC_DER_B64="$(openssl pkey -in "$KEY_DIR/capability.pem" -pubout -outform DER | openssl base64 -A)"

umask 077
cat > "$TARGET" <<EOF
# Generated by init-env.sh for local use only. Never commit this file.
GUARD_RUNTIME_PROPOSAL_TOKEN=$(secret)
GUARD_RUNTIME_EXECUTOR_TOKEN=$(secret)
SECURITY_API_KEY=$(secret)
AUDIT_INTEGRITY_KEY=$(secret)
OPERATOR_PASSWORD=$(secret)
# Bearer token for agents calling /mcp. Leave empty to keep MCP disabled.
MCP_TOKEN=$(secret)
REMEDIATION_AUTH_PRIVATE_KEY_PKCS8=$PRIVATE_DER_B64
REMEDIATION_AUTH_PUBLIC_KEY_SPKI=$PUBLIC_DER_B64
GUARD_RUNTIME_TENANT_ID=local
GUARD_RUNTIME_VERIFIED_EMAIL=soc@example.test
DASHBOARD_PORT=8088
# Optional AI provider for "Ask agent": any OpenAI-compatible chat-completions endpoint (OpenAI, Azure OpenAI,
# Claude's compatibility layer, or a local Ollama/vLLM server; set AI_ALLOW_INSECURE_HTTP=true for plain-HTTP internal hosts).
AI_PROVIDER=disabled
AI_API_URL=https://api.openai.com/v1/chat/completions
AI_API_KEY=
AI_MODEL=
AI_ALLOW_INSECURE_HTTP=false
EOF
echo "Wrote $TARGET. Start the stack with: docker compose up --build"
